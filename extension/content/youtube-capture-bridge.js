(() => {
  // Word-timed json3 for a long video passes 3 MB, so the cap only guards against runaway bodies.
  const MAX_CAPTION_CHARS = 32 * 1024 * 1024;
  const cache = new Map();
  const pending = new Set();
  function matches(caption, request) {
    return caption.videoId === request.videoId
      && (!request.languageCode || caption.languageCode === request.languageCode)
      && (request.isAutoGenerated === undefined || caption.isAutoGenerated === request.isAutoGenerated);
  }
  function get(request) {
    return [...cache.values()].reverse().find((caption) => matches(caption, request)) || null;
  }
  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== "ast.youtube.captionData") return;
    const caption = event.data.caption;
    if (!caption || !/^[\w-]{11}$/.test(caption.videoId || "")
      || !/^[\w-]{1,35}$/.test(caption.languageCode || "")
      || typeof caption.isAutoGenerated !== "boolean"
      || typeof caption.text !== "string" || !caption.text.trim() || caption.text.length > MAX_CAPTION_CHARS) return;
    const key = `${caption.videoId}:${caption.languageCode}:${caption.isAutoGenerated}`;
    cache.delete(key);
    cache.set(key, caption);
    if (cache.size > 6) cache.delete(cache.keys().next().value);
    for (const waiter of pending) {
      if (matches(caption, waiter.request)) waiter.finish(caption);
    }
  });
  // The player has no track for this request, so its waiter ends now with no caption.
  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== "ast.youtube.captionUnavailable") return;
    const request = event.data.request;
    if (!/^[\w-]{11}$/.test(request?.videoId || "")) return;
    for (const waiter of pending) {
      if (waiter.request.videoId === request.videoId
        && waiter.request.languageCode === request.languageCode
        && waiter.request.isAutoGenerated === request.isAutoGenerated) waiter.finish(null);
    }
  });
  const targetWaiters = new Set();
  const trackWaiters = new Set();
  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== "ast.youtube.trackList") return;
    const { videoId, tracks } = event.data;
    if (!Array.isArray(tracks)) return;
    const valid = tracks.filter((track) => /^[\w-]{1,35}$/.test(track?.languageCode || "")
      && typeof track.name === "string" && typeof track.baseUrl === "string");
    for (const waiter of trackWaiters) {
      if (waiter.videoId === videoId) waiter.finish(valid);
    }
  });
  const targetResults = new Map();
  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== "ast.youtube.targetCaptionResult") return;
    const result = event.data.result;
    for (const waiter of targetWaiters) {
      if (result?.videoId !== waiter.request.videoId || result.targetLanguage !== waiter.request.targetLanguage) continue;
      const caption = result.caption;
      const valid = caption && ["human", "auto"].includes(caption.source)
        && /^[\w-]{1,35}$/.test(caption.languageCode || "")
        && typeof caption.text === "string" && caption.text.trim() && caption.text.length <= MAX_CAPTION_CHARS;
      waiter.finish(valid
        ? { videoId: result.videoId, languageCode: caption.languageCode, source: caption.source, text: caption.text }
        : null);
    }
  });
  globalThis.astYoutubeCaptionCapture = {
    get,
    request(request) {
      const cached = get(request);
      if (cached) return Promise.resolve(cached);
      return new Promise((resolve) => {
        const waiter = { request, finish(caption) {
          clearTimeout(timeout);
          pending.delete(waiter);
          resolve(caption);
        } };
        const timeout = setTimeout(() => waiter.finish(null), 10000);
        pending.add(waiter);
        window.postMessage({ type: "ast.youtube.captionRequest", request }, location.origin);
      });
    },
    // The player's own track list for a video, once the player has switched to it; null on timeout.
    listTracks(videoId) {
      return new Promise((resolve) => {
        const waiter = { videoId, finish(tracks) {
          clearTimeout(timeout);
          trackWaiters.delete(waiter);
          resolve(tracks);
        } };
        const timeout = setTimeout(() => waiter.finish(null), 4500);
        trackWaiters.add(waiter);
        window.postMessage({ type: "ast.youtube.trackListRequest", videoId }, location.origin);
      });
    },
    // Asks the page for a human caption track in the target language; resolves null when there is none.
    requestTarget(request) {
      // The page makes one attempt per video and language, so later calls reuse that answer.
      const key = `${request.videoId}:${request.targetLanguage}`;
      if (targetResults.has(key)) return Promise.resolve(targetResults.get(key));
      return new Promise((resolve) => {
        const waiter = { request, finish(caption) {
          clearTimeout(timeout);
          targetWaiters.delete(waiter);
          targetResults.delete(key);
          targetResults.set(key, caption);
          if (targetResults.size > 6) targetResults.delete(targetResults.keys().next().value);
          resolve(caption);
        } };
        const timeout = setTimeout(() => waiter.finish(null), 5000);
        targetWaiters.add(waiter);
        window.postMessage({ type: "ast.youtube.targetCaptionRequest", request }, location.origin);
      });
    }
  };
})();
