(() => {
  // Word-timed json3 for a long video passes 3 MB, so the cap only guards against runaway bodies.
  const MAX_CAPTION_CHARS = 32 * 1024 * 1024;
  const DATA_EVENT = "ast.youtube.captionData";
  const REQUEST_EVENT = "ast.youtube.captionRequest";
  const TARGET_REQUEST_EVENT = "ast.youtube.targetCaptionRequest";
  const TARGET_RESULT_EVENT = "ast.youtube.targetCaptionResult";
  const TRACKS_REQUEST_EVENT = "ast.youtube.trackListRequest";
  const TRACKS_EVENT = "ast.youtube.trackList";
  const PLAYER_WAIT_ATTEMPTS = 16;
  const PLAYER_WAIT_MS = 250;
  const cache = new Map();
  // Signed player URLs stay in the page; they are only reused here to ask for another track.
  const playerUrls = new Map();
  const trackUrls = new Map();
  const targetAttempts = new Set();
  let restorePlayer = null;
  const inflight = new Set();

  function isRequestedUrl(rawUrl, request) {
    try {
      const url = new URL(rawUrl, location.origin);
      return url.origin === location.origin && url.pathname === "/api/timedtext"
        && (!request.videoId || url.searchParams.get("v") === request.videoId)
        && (!request.languageCode || url.searchParams.get("lang") === request.languageCode)
        && (request.isAutoGenerated === undefined || (url.searchParams.get("kind") === "asr") === request.isAutoGenerated);
    } catch { return false; }
  }

  function matches(caption, request) {
    return caption.videoId === request.videoId
      && (!request.languageCode || caption.languageCode === request.languageCode)
      && (request.isAutoGenerated === undefined || caption.isAutoGenerated === request.isAutoGenerated);
  }

  function capture(rawUrl, text) {
    try {
      const url = new URL(rawUrl, location.origin);
      if (url.origin !== "https://www.youtube.com" || url.pathname !== "/api/timedtext"
        || url.searchParams.has("tlang") || !text?.trim() || text.length > MAX_CAPTION_CHARS) return;
      const caption = {
        videoId: url.searchParams.get("v"),
        languageCode: url.searchParams.get("lang"),
        isAutoGenerated: url.searchParams.get("kind") === "asr",
        text
      };
      if (!/^[\w-]{11}$/.test(caption.videoId || "") || !caption.languageCode) return;
      const key = `${caption.videoId}:${caption.languageCode}:${caption.isAutoGenerated}`;
      for (const [map, mapKey] of [[playerUrls, caption.videoId], [trackUrls, key]]) {
        map.delete(mapKey);
        map.set(mapKey, url.toString());
        if (map.size > 6) map.delete(map.keys().next().value);
      }
      cache.delete(key);
      cache.set(key, caption);
      if (cache.size > 6) cache.delete(cache.keys().next().value);
      // Forward only caption metadata and body, never signed URLs or headers.
      window.postMessage({ type: DATA_EVENT, caption }, location.origin);
      if (restorePlayer && matches(caption, restorePlayer.request)) restorePlayer.finish();
    } catch { /* A failed observer must not affect the player's requests. */ }
  }

  const originalFetch = window.fetch;
  window.fetch = function (...args) {
    const rawUrl = typeof args[0] === "string" ? args[0] : args[0]?.url;
    const pending = { url: rawUrl };
    if (rawUrl && isRequestedUrl(rawUrl, {})) inflight.add(pending);
    const result = originalFetch.apply(this, args);
    result.finally(() => inflight.delete(pending)).catch(() => {});
    result.then((response) => {
      const url = new URL(response.url, location.origin);
      if (response.ok && url.origin === "https://www.youtube.com" && url.pathname === "/api/timedtext") {
        response.clone().text().then((text) => capture(response.url, text)).catch(() => {});
      }
    }).catch(() => {});
    return result;
  };

  const originalOpen = XMLHttpRequest.prototype.open;
  XMLHttpRequest.prototype.open = function (...args) {
    const url = new URL(String(args[1]), location.origin);
    if (url.origin === "https://www.youtube.com" && url.pathname === "/api/timedtext") {
      const pending = { url: url.toString() };
      inflight.add(pending);
      this.addEventListener("loadend", () => inflight.delete(pending), { once: true });
      this.addEventListener("load", () => {
        try {
          if (this.status < 200 || this.status >= 300) return;
          const text = this.responseType === "json" ? JSON.stringify(this.response) : this.responseText;
          capture(this.responseURL, text);
        } catch { /* Non-text responses are not caption documents. */ }
      }, { once: true });
    }
    return originalOpen.apply(this, args);
  };

  function matchesTargetLanguage(trackLanguage, targetLanguage) {
    const track = String(trackLanguage || "").toLowerCase();
    const target = String(targetLanguage || "").toLowerCase();
    if (track === target) return true;
    if (target === "zh-cn") return ["zh-hans", "zh-sg"].includes(track);
    if (target === "zh-tw") return ["zh-hant", "zh-hk"].includes(track);
    // A regionless target such as "ko" or "pt" accepts any regional variant of that language.
    return !target.includes("-") && track.split("-")[0] === target;
  }

  async function fetchCaptionText(url) {
    const result = await originalFetch.call(window, url.toString(), { credentials: "include" });
    if (!result.ok) return "";
    const text = await result.text();
    return text.trim() && text.length <= MAX_CAPTION_CHARS ? text : "";
  }

  // Human captions in the target language come first; YouTube's machine translation of the
  // source track (tlang) is the fallback. Both reuse a signed URL the player already requested.
  async function fetchTargetCaption(request) {
    const player = document.getElementById("movie_player");
    const response = player?.getPlayerResponse?.();
    if (response?.videoDetails?.videoId !== request.videoId) return null;
    const renderer = response.captions?.playerCaptionsTracklistRenderer;
    const tracks = player.getOption?.("captions", "tracklist")?.length ? player.getOption("captions", "tracklist")
      : renderer?.captionTracks || [];
    const preferExact = (items, code) => items.find((item) => item.languageCode.toLowerCase() === code.toLowerCase()) || items[0];
    const humanTrack = preferExact(tracks.filter((track) => track.kind !== "asr" && track.languageCode
      && matchesTargetLanguage(track.languageCode, request.targetLanguage)), request.targetLanguage);
    const playerUrl = playerUrls.get(request.videoId);
    if (humanTrack && playerUrl) {
      const url = new URL(playerUrl);
      url.searchParams.set("lang", humanTrack.languageCode);
      url.searchParams.set("fmt", "json3");
      for (const name of ["kind", "tlang", "name"]) url.searchParams.delete(name);
      const text = await fetchCaptionText(url);
      if (text) return { languageCode: humanTrack.languageCode, source: "human", text };
    }

    const sourceUrl = request.sourceLanguage
      && trackUrls.get(`${request.videoId}:${request.sourceLanguage}:${Boolean(request.sourceIsAutoGenerated)}`);
    const translationLanguage = preferExact((renderer?.translationLanguages || [])
      .filter((language) => language.languageCode && matchesTargetLanguage(language.languageCode, request.targetLanguage)), request.targetLanguage);
    if (!sourceUrl || !translationLanguage) return null;
    const url = new URL(sourceUrl);
    url.searchParams.set("tlang", translationLanguage.languageCode);
    url.searchParams.set("fmt", "json3");
    const text = await fetchCaptionText(url);
    return text ? { languageCode: translationLanguage.languageCode, source: "auto", text } : null;
  }

  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== TARGET_REQUEST_EVENT) return;
    const request = event.data.request;
    const language = /^[a-z]{2,3}(?:-[a-z0-9]{2,8})?$/i;
    if (!/^[\w-]{11}$/.test(request?.videoId || "") || !language.test(request.targetLanguage || "")
      || (request.sourceLanguage !== undefined && !language.test(request.sourceLanguage))) return;
    const reply = (caption) => window.postMessage({
      type: TARGET_RESULT_EVENT,
      result: { videoId: request.videoId, targetLanguage: request.targetLanguage, caption }
    }, location.origin);
    // One attempt per video and language keeps a missing or rate-limited track from being requested again.
    const attemptKey = `${request.videoId}:${request.targetLanguage}`;
    if (targetAttempts.has(attemptKey)) {
      reply(null);
      return;
    }
    targetAttempts.add(attemptKey);
    fetchTargetCaption(request).then(reply, () => reply(null));
  });

  // Right after switching videos the player still describes the previous one; wait briefly for it.
  function whenPlayerShows(videoId, callback, attempts = PLAYER_WAIT_ATTEMPTS) {
    const player = document.getElementById("movie_player");
    let response = null;
    try { response = player?.getPlayerResponse?.(); } catch { /* The player may be navigating. */ }
    if (response?.videoDetails?.videoId === videoId) {
      callback(player, response);
    } else if (attempts > 0) {
      setTimeout(() => whenPlayerShows(videoId, callback, attempts - 1), PLAYER_WAIT_MS);
    }
  }

  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== TRACKS_REQUEST_EVENT) return;
    const videoId = event.data.videoId;
    if (!/^[\w-]{11}$/.test(videoId || "")) return;
    whenPlayerShows(videoId, (_player, response) => {
      // Track metadata only; caption bodies still arrive through the player's own requests.
      const tracks = (response.captions?.playerCaptionsTracklistRenderer?.captionTracks || [])
        .filter((track) => track?.languageCode)
        .map((track) => ({
          languageCode: track.languageCode,
          kind: track.kind === "asr" ? "asr" : "",
          name: track.name?.simpleText || track.name?.runs?.map((run) => run.text).join("") || "",
          baseUrl: typeof track.baseUrl === "string" ? track.baseUrl : ""
        }));
      window.postMessage({ type: TRACKS_EVENT, videoId, tracks }, location.origin);
    });
  });

  window.addEventListener("message", (event) => {
    if (event.source !== window || event.origin !== location.origin || event.data?.type !== REQUEST_EVENT) return;
    const request = event.data.request;
    if (!/^[\w-]{11}$/.test(request?.videoId || "")
      || (request.languageCode !== undefined && !/^[\w-]{1,35}$/.test(request.languageCode))
      || (request.isAutoGenerated !== undefined && typeof request.isAutoGenerated !== "boolean")) return;
    const cached = [...cache.values()].reverse().find((caption) => matches(caption, request));
    if (cached) {
      window.postMessage({ type: DATA_EVENT, caption: cached }, location.origin);
      return;
    }
    whenPlayerShows(request.videoId, (player, response) => requestFromPlayer(request, player, response));
  });

  // Ask the current native player to acquire its own authenticated caption
  // response, then restore the user's caption visibility and selected track.
  function requestFromPlayer(request, player, response) {
    if (!player?.getPlayerResponse || !player.setOption || !player.toggleSubtitles) return;
    if (player.classList?.contains("ad-showing") || player.classList?.contains("ad-interrupting")) return;
    try {
      const nativeTracks = player.getOption?.("captions", "tracklist");
      const tracks = nativeTracks?.length ? nativeTracks
        : response.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
      const candidates = tracks.filter((track) => (!request.languageCode || track.languageCode === request.languageCode)
        && (request.isAutoGenerated === undefined || (track.kind === "asr") === request.isAutoGenerated));
      const track = candidates.find((item) => /^en(?:-|$)/i.test(item.languageCode) && item.kind !== "asr")
        || candidates.find((item) => /^en(?:-|$)/i.test(item.languageCode))
        || candidates.find((item) => item.kind !== "asr") || candidates[0];
      if (!track) return;
      restorePlayer?.finish();
      const wasOn = player.querySelector(".ytp-subtitles-button")?.getAttribute("aria-pressed") === "true";
      const previousTrack = player.getOption?.("captions", "track");
      let timeout;
      let activationTimeout;
      let retryTimeout;
      const finish = () => {
        clearTimeout(timeout);
        clearTimeout(activationTimeout);
        clearTimeout(retryTimeout);
        restorePlayer = null;
        if (player.getPlayerResponse()?.videoDetails?.videoId !== request.videoId) return;
        if (previousTrack?.languageCode) player.setOption("captions", "track", previousTrack);
        const isOn = player.querySelector(".ytp-subtitles-button")?.getAttribute("aria-pressed") === "true";
        if (isOn !== wasOn) player.toggleSubtitles();
      };
      restorePlayer = { request, finish };
      timeout = setTimeout(finish, 6000);
      const activate = () => {
        if (player.getPlayerResponse()?.videoDetails?.videoId !== request.videoId) return;
        if (player.querySelector(".ytp-subtitles-button")?.getAttribute("aria-pressed") !== "true") player.toggleSubtitles();
        player.setOption("captions", "track", track);
      };
      retryTimeout = setTimeout(() => {
        if ([...inflight].some((item) => isRequestedUrl(item.url, request))) return;
        if (player.getPlayerResponse()?.videoDetails?.videoId !== request.videoId
          || player.classList?.contains("ad-showing") || player.classList?.contains("ad-interrupting")) return;
        const alternate = tracks.find((item) => item !== track);
        if (alternate) {
          player.setOption("captions", "track", alternate);
          activationTimeout = setTimeout(activate, 150);
        } else {
          player.toggleSubtitles();
          activationTimeout = setTimeout(activate, 150);
        }
      }, 2500);
      if (wasOn && previousTrack?.languageCode === track.languageCode && previousTrack.kind === track.kind) {
        player.toggleSubtitles();
        activationTimeout = setTimeout(activate, 150);
      } else {
        activate();
      }
    } catch {
      try { restorePlayer?.finish(); } catch { /* The player may be navigating. */ }
    }
  }
})();
