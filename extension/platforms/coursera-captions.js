import { createSubtitleDocument, parseWebVtt } from "../shared/subtitles.js";

const COURSERA_HOSTS = new Set(["www.coursera.org", "coursera.org"]);
const COURSERA_SUBTITLE_PATH_PREFIX = "/api/subtitleAssetProxy.v1/";

export function isCourseraCaptionUrl(value) {
  try {
    const url = new URL(String(value || ""));
    return url.protocol === "https:"
      && COURSERA_HOSTS.has(url.hostname)
      && url.pathname.startsWith(COURSERA_SUBTITLE_PATH_PREFIX)
      && url.pathname.length > COURSERA_SUBTITLE_PATH_PREFIX.length
      && url.searchParams.get("fileExtension") === "vtt";
  } catch {
    return false;
  }
}

function isMachineTranslated(tags) {
  return Array.isArray(tags)
    && tags.some((tag) => tag?.name === "machineTranslation" && String(tag.value) === "true");
}

// Builds the track list from a Coursera `onDemandVideos.v1` / page `videoData` object.
// Machine-translated tracks are flagged so the original-language track is the default source.
export function normalizeCourseraSubtitleTracks(videoData, { videoId, baseUrl = "https://www.coursera.org/" } = {}) {
  const vtt = videoData?.subtitlesVtt;
  if (!vtt || typeof vtt !== "object" || !videoId) return [];

  const tracks = [];
  for (const [languageCode, path] of Object.entries(vtt)) {
    let url;
    try {
      url = new URL(String(path || ""), baseUrl);
    } catch {
      continue;
    }
    if (!isCourseraCaptionUrl(url)) continue;
    tracks.push({
      videoId: String(videoId),
      languageCode,
      label: languageCode,
      isAutoGenerated: isMachineTranslated(videoData?.subtitlesAssetTags?.[languageCode]),
      url: url.href
    });
  }
  return tracks;
}

async function fetchText(url) {
  const response = await fetch(url, {
    redirect: "error",
    headers: { Accept: "text/vtt,text/plain,*/*" }
  });
  const text = await response.text();
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
  return text;
}

export async function fetchCourseraTranscript({ videoId, trackUrl, sourceLanguage }) {
  if (!videoId) throw new Error("Coursera videoId is required.");
  if (!isCourseraCaptionUrl(trackUrl)) throw new Error("Coursera caption URL is invalid.");

  const cues = parseWebVtt(await fetchText(trackUrl), { idPrefix: "coursera" });
  return createSubtitleDocument({
    platform: "coursera",
    videoId: String(videoId),
    sourceLanguage: String(sourceLanguage || "en"),
    cues
  });
}
