import { createSubtitleDocument, parseWebVtt } from "../shared/subtitles.js";

const NVIDIA_ONDEMAND_CAPTIONS_URL = "https://api-prod.nvidia.com/services/nod/api/v1/session/captions";
const SESSION_ID_PATTERN = /^[\w.-]{1,120}$/;
const LANGUAGE_CODE_PATTERN = /^[\w-]{1,35}$/;

export function isNvidiaOnDemandSessionId(value) {
  return SESSION_ID_PATTERN.test(String(value || ""));
}

export function getNvidiaOnDemandCaptionsUrl(sessionId, languageCode = "en") {
  if (!isNvidiaOnDemandSessionId(sessionId) || !LANGUAGE_CODE_PATTERN.test(String(languageCode || ""))) return "";
  const url = new URL(NVIDIA_ONDEMAND_CAPTIONS_URL);
  url.searchParams.set("sessionID", sessionId);
  url.searchParams.set("languagecode", languageCode);
  return url.href;
}

// Response shape: { objects: [{ languageCode, label, id, ... }], body: "<SRT text of the requested language>" }.
export function listNvidiaOnDemandTracks(response, { sessionId } = {}) {
  const objects = Array.isArray(response?.objects) ? response.objects : [];
  const seen = new Set();
  return objects
    .filter((item) => item?.languageCode && !seen.has(item.languageCode) && seen.add(item.languageCode))
    .map((item) => ({
      sessionId: String(sessionId || ""),
      languageCode: String(item.languageCode),
      label: String(item.label || item.language || item.languageCode),
      isAutoGenerated: /auto[- ]?generated/i.test(String(item.label || ""))
    }));
}

async function fetchCaptions(sessionId, languageCode) {
  const url = getNvidiaOnDemandCaptionsUrl(sessionId, languageCode);
  if (!url) throw new Error("NVIDIA On-Demand session id or language is invalid.");
  const response = await fetch(url, {
    redirect: "error",
    headers: { Accept: "application/json" }
  });
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
  return response.json();
}

export async function fetchNvidiaOnDemandTracks({ sessionId }) {
  return listNvidiaOnDemandTracks(await fetchCaptions(sessionId, "en"), { sessionId });
}

export async function fetchNvidiaOnDemandTranscript({ sessionId, sourceLanguage }) {
  const languageCode = String(sourceLanguage || "en");
  const response = await fetchCaptions(sessionId, languageCode);
  if (typeof response?.body !== "string" || !response.body.trim()) {
    throw new Error("No NVIDIA On-Demand captions available for this video.");
  }

  // The body is SRT; the WebVTT parser accepts its comma timestamps and numeric cue ids.
  return createSubtitleDocument({
    platform: "nvidiaOnDemand",
    videoId: String(sessionId),
    sourceLanguage: languageCode,
    cues: parseWebVtt(response.body, { idPrefix: "nvidia-ondemand" })
  });
}
