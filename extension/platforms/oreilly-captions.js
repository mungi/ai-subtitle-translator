import { createSubtitleDocument, parseWebVtt } from "../shared/subtitles.js";

const OREILLY_ORIGIN = "https://www.oreilly.com";
const CLIP_ID_PATTERN = /^[\w.-]{1,120}$/;

export function isOreillyClipId(value) {
  return CLIP_ID_PATTERN.test(String(value || ""));
}

export function getOreillyVideoClipUrl(clipId) {
  if (!isOreillyClipId(clipId)) return "";
  return `${OREILLY_ORIGIN}/api/v1/videoclips/${encodeURIComponent(clipId)}/`;
}

function hasUsableLines(transcription) {
  return Array.isArray(transcription?.lines) && transcription.lines.length > 0;
}

// The clip API lists a transcript per language: { language, transcription: { lines: [{ begin, end, text }] } }.
export function listOreillyTracks(clip, { clipId } = {}) {
  const transcriptions = Array.isArray(clip?.transcriptions) ? clip.transcriptions : [];
  const seen = new Set();
  return transcriptions
    .filter((item) => item?.language && hasUsableLines(item.transcription) && !seen.has(item.language) && seen.add(item.language))
    .map((item) => ({
      clipId: String(clipId || clip?.reference_id || ""),
      languageCode: String(item.language),
      label: String(item.language),
      isAutoGenerated: false
    }));
}

export function oreillyLinesToCues(lines) {
  // WebVTT parsing also repairs zero-length cues and validates ordering.
  const vtt = ["WEBVTT", ""];
  for (const line of lines) {
    const text = String(line?.text ?? "").trim();
    if (!text || !line?.begin || !line?.end) continue;
    vtt.push(`${line.begin} --> ${line.end}`, text.replace(/-->/g, "->"), "");
  }
  return parseWebVtt(vtt.join("\n"), { idPrefix: "oreilly" });
}

async function fetchClip(clipId) {
  const url = getOreillyVideoClipUrl(clipId);
  if (!url) throw new Error("O'Reilly clip id is invalid.");
  const response = await fetch(url, {
    redirect: "error",
    credentials: "include",
    headers: { Accept: "application/json" }
  });
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
  return response.json();
}

export async function fetchOreillyTracks({ clipId }) {
  return listOreillyTracks(await fetchClip(clipId), { clipId });
}

export async function fetchOreillyTranscript({ clipId, sourceLanguage }) {
  const clip = await fetchClip(clipId);
  const transcripts = Array.isArray(clip?.transcriptions) ? clip.transcriptions : [];
  const wanted = String(sourceLanguage || "");
  const match = transcripts.find((item) => item?.language === wanted && hasUsableLines(item.transcription))
    || transcripts.find((item) => hasUsableLines(item?.transcription));
  if (!match) throw new Error("No O'Reilly captions available for this video.");

  return createSubtitleDocument({
    platform: "oreilly",
    videoId: String(clipId),
    sourceLanguage: String(match.language),
    cues: oreillyLinesToCues(match.transcription.lines)
  });
}
