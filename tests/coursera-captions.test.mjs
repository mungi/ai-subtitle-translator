import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import {
  fetchCourseraTranscript,
  isCourseraCaptionUrl,
  normalizeCourseraSubtitleTracks
} from "../extension/platforms/coursera-captions.js";
import { validateBackgroundMessage } from "../extension/shared/message-contracts.js";

const EN_VTT = "/api/subtitleAssetProxy.v1/Awz_0NyPS8mM_9Dcj9vJCA?expiry=1794182400000&hmac=abc&fileExtension=vtt";
const KO_VTT = "/api/subtitleAssetProxy.v1/DJhPFEwdQMiYTxRMHXDISQ?expiry=1794182400000&hmac=def&fileExtension=vtt";

test("Coursera caption URLs are limited to the signed VTT subtitle proxy", () => {
  assert.equal(isCourseraCaptionUrl(`https://www.coursera.org${EN_VTT}`), true);
  assert.equal(isCourseraCaptionUrl(`http://www.coursera.org${EN_VTT}`), false);
  assert.equal(isCourseraCaptionUrl(`https://evil.example${EN_VTT}`), false);
  assert.equal(isCourseraCaptionUrl("https://www.coursera.org/api/other.v1/abc?fileExtension=vtt"), false);
  assert.equal(isCourseraCaptionUrl(`https://www.coursera.org${EN_VTT.replace("vtt", "srt")}`), false);
  assert.equal(isCourseraCaptionUrl("https://www.coursera.org/api/subtitleAssetProxy.v1/?fileExtension=vtt"), false);
});

test("Coursera tracks come from subtitlesVtt and flag machine translations", () => {
  const tracks = normalizeCourseraSubtitleTracks({
    subtitles: { en: "/api/subtitleAssetProxy.v1/x?fileExtension=srt" },
    subtitlesVtt: { en: EN_VTT, ko: KO_VTT, bad: "https://evil.example/a.vtt" },
    subtitlesAssetTags: {
      ko: [{ name: "machineTranslation", value: "true" }, { name: "machineTranslationProvider", value: "AMAZON" }]
    }
  }, { videoId: "iXgwH" });

  assert.deepEqual(tracks.map((track) => [track.languageCode, track.isAutoGenerated]), [["en", false], ["ko", true]]);
  assert.equal(tracks[0].url, `https://www.coursera.org${EN_VTT}`);
  assert.deepEqual(normalizeCourseraSubtitleTracks({ subtitles: {} }, { videoId: "iXgwH" }), []);
});

test("Coursera VTT captions become a coursera subtitle document", async () => {
  const previousFetch = globalThis.fetch;
  globalThis.fetch = async (url, init) => {
    assert.equal(url, `https://www.coursera.org${EN_VTT}`);
    assert.equal(init.redirect, "error");
    return new Response("WEBVTT\n\n1\n00:00:06.540 --> 00:00:08.860\nWelcome to the introduction to\n\n2\n00:00:08.860 --> 00:00:12.340\nthe AI Infrastructure and\nOperations Fundamentals course.\n", {
      status: 200,
      headers: { "Content-Type": "text/vtt" }
    });
  };

  try {
    const document = await fetchCourseraTranscript({
      videoId: "iXgwH",
      trackUrl: `https://www.coursera.org${EN_VTT}`,
      sourceLanguage: "en"
    });
    assert.deepEqual(document, {
      platform: "coursera",
      videoId: "iXgwH",
      sourceLanguage: "en",
      cues: [
        { id: "1", start: 6.54, end: 8.86, text: "Welcome to the introduction to" },
        { id: "2", start: 8.86, end: 12.34, text: "the AI Infrastructure and Operations Fundamentals course." }
      ]
    });
    await assert.rejects(
      fetchCourseraTranscript({ videoId: "iXgwH", trackUrl: "https://evil.example/a.vtt" }),
      /Coursera caption URL is invalid/
    );
  } finally {
    globalThis.fetch = previousFetch;
  }
});

test("Coursera fetch messages are validated and accepted from lecture pages only", () => {
  assert.equal(validateBackgroundMessage({ type: "captions.coursera.fetchTranscript", videoId: "iXgwH" }).error, "trackUrl is required.");
  assert.equal(validateBackgroundMessage({
    type: "captions.coursera.fetchTranscript",
    videoId: "iXgwH",
    trackUrl: `https://www.coursera.org${EN_VTT}`,
    sourceLanguage: "en"
  }).error, undefined);
});

test("content script wires Coursera lecture detection and the platform handler", async () => {
  const contentScript = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  assert.match(contentScript, /host === "www\.coursera\.org" \|\| host === "coursera\.org"\) return "coursera"/);
  assert.match(contentScript, /\\\/learn\\\/\(\[\^\/\]\+\)\\\/lecture\\\/\(\[\^\/\?#\]\+\)/);
  assert.match(contentScript, /type: "captions\.coursera\.fetchTranscript"/);
  assert.match(contentScript, /onDemandLectureVideos\.v1/);
});
