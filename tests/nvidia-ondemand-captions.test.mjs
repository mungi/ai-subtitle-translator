import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import {
  fetchNvidiaOnDemandTracks,
  fetchNvidiaOnDemandTranscript,
  getNvidiaOnDemandCaptionsUrl,
  isNvidiaOnDemandSessionId,
  listNvidiaOnDemandTracks
} from "../extension/platforms/nvidia-ondemand-captions.js";
import { validateBackgroundMessage, validateMessageSender } from "../extension/shared/message-contracts.js";

const RESPONSE = {
  objects: [{ language: "English", languageCode: "en", id: "1_zr27zmn5", label: "English (auto-generated)", displayOnPlayer: true }],
  body: "0\n00:00:09,502 --> 00:00:13,568\nThis is how intelligence is made\n\n1\n00:00:14,821 --> 00:00:22,253\nA new kind of factory, generator\nof tokens, building blocks of AI.\n"
};

test("NVIDIA On-Demand session ids and API URLs are restricted", () => {
  assert.equal(isNvidiaOnDemandSessionId("gtcberlin26-sb61112"), true);
  assert.equal(isNvidiaOnDemandSessionId("../x"), false);
  assert.equal(
    getNvidiaOnDemandCaptionsUrl("gtcberlin26-sb61112", "en"),
    "https://api-prod.nvidia.com/services/nod/api/v1/session/captions?sessionID=gtcberlin26-sb61112&languagecode=en"
  );
  assert.equal(getNvidiaOnDemandCaptionsUrl("a/b", "en"), "");
  assert.equal(getNvidiaOnDemandCaptionsUrl("ok", "e n"), "");
});

test("NVIDIA On-Demand tracks flag auto-generated captions", () => {
  const tracks = listNvidiaOnDemandTracks(RESPONSE, { sessionId: "gtcberlin26-sb61112" });
  assert.deepEqual(tracks.map((track) => [track.languageCode, track.isAutoGenerated]), [["en", true]]);
  assert.deepEqual(listNvidiaOnDemandTracks({}), []);
});

test("NVIDIA On-Demand SRT bodies become a nvidiaOnDemand subtitle document", async () => {
  const previousFetch = globalThis.fetch;
  const seen = [];
  globalThis.fetch = async (url, init) => {
    seen.push(url);
    assert.equal(init.redirect, "error");
    return new Response(JSON.stringify(RESPONSE), { status: 200, headers: { "Content-Type": "application/json" } });
  };
  try {
    const tracks = await fetchNvidiaOnDemandTracks({ sessionId: "gtcberlin26-sb61112" });
    assert.equal(tracks.length, 1);
    const document = await fetchNvidiaOnDemandTranscript({ sessionId: "gtcberlin26-sb61112", sourceLanguage: "en" });
    assert.deepEqual(document, {
      platform: "nvidiaOnDemand",
      videoId: "gtcberlin26-sb61112",
      sourceLanguage: "en",
      cues: [
        { id: "0", start: 9.502, end: 13.568, text: "This is how intelligence is made" },
        { id: "1", start: 14.821, end: 22.253, text: "A new kind of factory, generator of tokens, building blocks of AI." }
      ]
    });
    assert.ok(seen.every((url) => url.startsWith("https://api-prod.nvidia.com/")));
    await assert.rejects(fetchNvidiaOnDemandTranscript({ sessionId: "../x" }), /invalid/);
    globalThis.fetch = async () => new Response(JSON.stringify({ objects: [], body: "" }), { status: 200 });
    await assert.rejects(fetchNvidiaOnDemandTranscript({ sessionId: "ok" }), /No NVIDIA On-Demand captions available/);
  } finally {
    globalThis.fetch = previousFetch;
  }
});

test("NVIDIA On-Demand messages are validated, accepted from session pages only, and the player is wired", async () => {
  assert.match(validateBackgroundMessage({ type: "captions.nvidiaOnDemand.listTracks", sessionId: "../x" }).error, /sessionId is invalid/);
  assert.equal(validateBackgroundMessage({ type: "captions.nvidiaOnDemand.fetchTranscript", sessionId: "gtcberlin26-sb61112", sourceLanguage: "en" }).error, undefined);

  const message = { type: "captions.nvidiaOnDemand.listTracks", sessionId: "gtcberlin26-sb61112" };
  const sender = (url) => ({ id: "extension-id", url, tab: { id: 5, url } });
  assert.equal(validateMessageSender(message, sender("https://www.nvidia.com/en-us/on-demand/session/gtcberlin26-sb61112/?playlistId=x"), "extension-id").ok, true);
  assert.equal(validateMessageSender(message, sender("https://www.nvidia.com/en-us/ai-data-science/"), "extension-id").ok, false);

  const [contentScript, manifest] = await Promise.all([
    readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8"),
    readFile(new URL("../extension/manifest.json", import.meta.url), "utf8").then(JSON.parse)
  ]);
  assert.ok(manifest.content_scripts[0].matches.includes("https://www.nvidia.com/*/on-demand/session/*"));
  assert.match(contentScript, /host === "www\.nvidia\.com" && getNvidiaOnDemandSessionId\(\)\) return "nvidiaOnDemand"/);
  assert.match(contentScript, /type: "captions\.nvidiaOnDemand\.fetchTranscript"/);
  assert.match(contentScript, /const PLAYKIT_VIDEO_SELECTOR = "\.playkit-player video"/);
});
