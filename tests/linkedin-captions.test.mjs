import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import vm from "node:vm";
import { fetchLinkedinTranscript, isLinkedinCaptionUrl } from "../extension/platforms/linkedin-captions.js";
import { validateBackgroundMessage } from "../extension/shared/message-contracts.js";

const EN = "https://dms.licdn.com/playlist/vid/v2/D560DAQELOVhAjmbsbQ/video-captions-webvtt/B4EZb4SlX3HMCs-/0/0?e=1794035531&v=beta&t=abc";
const KO = "https://dms.licdn.com/playlist/vid/v2/D560DAQELOVhAjmbsbQ/video-captions-webvtt/B4EZekGOBrHYEg-/0/0?e=1794035531&v=beta&t=def";

test("LinkedIn caption URLs are limited to the licdn caption path", () => {
  assert.equal(isLinkedinCaptionUrl(EN), true);
  assert.equal(isLinkedinCaptionUrl(EN.replace("https:", "http:")), false);
  assert.equal(isLinkedinCaptionUrl(EN.replace("dms.licdn.com", "evil.example")), false);
  assert.equal(isLinkedinCaptionUrl("https://dms.licdn.com/playlist/vid/v2/x/mp4-720p/y/0/1"), false);
});

test("LinkedIn VTT captions become a linkedin subtitle document", async () => {
  const previousFetch = globalThis.fetch;
  globalThis.fetch = async (url, init) => {
    assert.equal(url, EN);
    assert.equal(init.redirect, "error");
    return new Response("WEBVTT\n\n1\n00:00:00.460 --> 00:00:04.620\nHow companies or industries are using\nthese AI technologies?\n", { status: 200 });
  };
  try {
    assert.deepEqual(await fetchLinkedinTranscript({ videoId: "ai-use-cases", trackUrl: EN, sourceLanguage: "en" }), {
      platform: "linkedin",
      videoId: "ai-use-cases",
      sourceLanguage: "en",
      cues: [{ id: "1", start: 0.46, end: 4.62, text: "How companies or industries are using these AI technologies?" }]
    });
    await assert.rejects(fetchLinkedinTranscript({ videoId: "x", trackUrl: "https://evil.example/a" }), /caption URL is invalid/);
  } finally {
    globalThis.fetch = previousFetch;
  }
});

function loadContentFunctions(source, names) {
  const sandbox = { URL };
  const code = names.map((name) => {
    const start = source.indexOf(`function ${name}(`);
    assert.ok(start >= 0, `${name} exists`);
    const end = source.indexOf("\n}\n", start) + 3;
    return source.slice(start, end);
  }).join("\n");
  vm.runInNewContext(`${code}\nthis.parse = parseLinkedinTranscriptTracks;`, sandbox);
  return sandbox;
}

test("lecture page HTML yields one track per language and flags machine translations", async () => {
  const source = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  const { parse } = loadContentFunctions(source, [
    "normalizeLinkedinCaptionUrl",
    "decodeLinkedinHtmlEntities",
    "extractLinkedinTranscriptsJson",
    "parseLinkedinTranscriptTracks"
  ]);
  const escape = (value) => JSON.stringify(value).replace(/"/g, "&quot;").replace(/=/g, "&#61;").replace(/&(?!quot;|#61;)/g, "&amp;");
  const html = `<code>{"a":[1],${escape({ transcripts: [
    { locale: { country: "US", language: "en" }, captionFile: EN, isAutogenerated: false },
    { locale: { country: "KR", language: "ko" }, captionFile: KO, isAutogenerated: true },
    { locale: { country: "XX", language: "xx" }, captionFile: "https://evil.example/x", isAutogenerated: true }
  ] }).slice(1, -1)},"after":"]"}</code>`;

  const tracks = [...parse(html)];
  assert.deepEqual(JSON.parse(JSON.stringify(tracks.map((track) => [track.languageCode, track.label, track.isAutoGenerated]))), [
    ["en", "en-US", false],
    ["ko", "ko-KR", true]
  ]);
  assert.equal(tracks[0].trackUrl, EN);
  assert.equal(parse("<html>no data</html>").length, 0);
});

test("LinkedIn fetch messages are validated and the player selectors are wired", async () => {
  assert.equal(validateBackgroundMessage({ type: "captions.linkedin.fetchTranscript", videoId: "x" }).error, "trackUrl is required.");
  assert.equal(validateBackgroundMessage({ type: "captions.linkedin.fetchTranscript", videoId: "x", trackUrl: EN }).error, undefined);
  const contentScript = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  assert.match(contentScript, /host === "www\.linkedin\.com" && location\.pathname\.startsWith\("\/learning\/"\)\) return "linkedin"/);
  assert.match(contentScript, /type: "captions\.linkedin\.fetchTranscript"/);
  assert.match(contentScript, /\.video-js \.vjs-control-bar/);
});

test("a zero-length cue is kept and shown until the next cue instead of failing the video", async () => {
  const { parseWebVtt } = await import("../extension/shared/subtitles.js");
  const cues = parseWebVtt("WEBVTT\n\n44\n00:01:55.000 --> 00:01:58.340\nbefore\n\n45\n00:01:58.340 --> 00:01:58.340\nthe topics expected into this particular\nexam.\n\n46\n00:01:59.000 --> 00:02:01.000\nnext\n\n47\n00:02:02.000 --> 00:02:02.000\nlast\n");
  assert.deepEqual(cues.map((cue) => [cue.start, cue.end]), [[115, 118.34], [118.34, 119], [119, 121], [122, 122.5]]);
  assert.equal(cues[1].text, "the topics expected into this particular exam.");
});

test("LinkedIn waits for the player's own video to have media before starting", async () => {
  const contentScript = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  assert.match(contentScript, /player && \(player\.readyState >= 1 \|\| player\.currentSrc\) \? player : null/);
  assert.doesNotMatch(contentScript, /LINKEDIN_VIDEO_SELECTOR\) \|\| document\.querySelector\("video"\)/);
});
