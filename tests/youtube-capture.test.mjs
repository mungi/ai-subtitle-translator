function withTranslationLanguages(h, languages) {
  const response = h.player.getPlayerResponse();
  response.captions.playerCaptionsTracklistRenderer.translationLanguages = languages;
  h.player.getPlayerResponse = () => response;
}

test("YouTube auto-translation requests tlang on the signed source track when no human track exists", async () => {
  const h = harness();
  const fetched = [];
  const koreanText = JSON.stringify({ events: [{ tStartMs: 1250, dDurationMs: 2500, segs: [{ utf8: "안녕 세상" }] }] });
  h.window.fetch = async (url) => {
    fetched.push(String(url));
    return { ok: true, url: String(url), text: async () => koreanText, clone: () => ({ text: async () => koreanText }) };
  };
  withTranslationLanguages(h, [{ languageCode: "ko" }, { languageCode: "ja" }]);
  h.bridge();
  h.main();
  h.xhr();
  const caption = await h.context.astYoutubeCaptionCapture.requestTarget({
    videoId, targetLanguage: "ko", sourceLanguage: "es", sourceIsAutoGenerated: true
  });
  assert.equal(caption.source, "auto");
  assert.equal(caption.languageCode, "ko");
  assert.equal(caption.text, koreanText);
  assert.equal(fetched.length, 1);
  const url = new URL(fetched[0]);
  assert.equal(url.searchParams.get("tlang"), "ko");
  assert.equal(url.searchParams.get("lang"), "es");
  assert.equal(url.searchParams.get("kind"), "asr");
  assert.equal(url.searchParams.get("pot"), "not-forwarded");
  // The translated response is not mistaken for a source caption.
  assert.equal(h.context.astYoutubeCaptionCapture.get({ videoId, languageCode: "ko" }), null);
});

