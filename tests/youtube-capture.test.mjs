test("YouTube track list waits for the player to show the requested video", async () => {
  const h = harness();
  const nextVideo = "zyx987wvu65";
  let playerVideo = videoId;
  const response = h.player.getPlayerResponse();
  h.player.getPlayerResponse = () => ({ ...response, videoDetails: { videoId: playerVideo } });
  h.bridge();
  h.main();
  const pending = h.context.astYoutubeCaptionCapture.listTracks(nextVideo);
  assert.equal(h.messages.some((message) => message.type === "ast.youtube.trackList"), false);

  playerVideo = nextVideo;
  // The newest timer is the player check; the older one is the bridge's own give-up timer.
  [...h.timeouts].at(-1)();
  const tracks = await pending;
  assert.deepEqual(JSON.parse(JSON.stringify(tracks)).map((track) => [track.languageCode, track.kind]), [["es", "asr"], ["en", ""]]);
});

test("YouTube capture keeps the word-timed captions of a long video", () => {
  const h = harness();
  h.bridge();
  h.main();
  // A three-hour lecture's json3 measured 3.4 MB in the player's own response.
  const longCaption = JSON.stringify({ events: [{ tStartMs: 0, dDurationMs: 1000, segs: [{ utf8: "word ".repeat(700_000) }] }] });
  h.xhr(captionUrl, longCaption);
  assert.equal(h.messages.at(-1).caption.text.length, longCaption.length);
  assert.equal(h.context.astYoutubeCaptionCapture.get({ videoId, languageCode: "es", isAutoGenerated: true })?.text.length, longCaption.length);
});
