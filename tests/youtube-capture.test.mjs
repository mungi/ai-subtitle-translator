test("YouTube target caption request reuses the signed player URL inside the page", async () => {
  const h = harness();
  const fetched = [];
  const englishText = JSON.stringify({ events: [{ tStartMs: 0, dDurationMs: 1000, segs: [{ utf8: "Hello" }] }] });
  h.window.fetch = async (url) => {
    fetched.push(String(url));
    return { ok: true, url: String(url), text: async () => englishText, clone: () => ({ text: async () => englishText }) };
  };
  h.bridge();
  h.main();
  h.xhr(`${captionUrl}&name=Spanish`);
  const caption = await h.context.astYoutubeCaptionCapture.requestTarget({ videoId, targetLanguage: "en" });
  assert.equal(caption.text, englishText);
  assert.equal(caption.languageCode, "en");
  assert.equal(caption.source, "human");
  assert.equal(fetched.length, 1);
  const url = new URL(fetched[0]);
  assert.equal(url.searchParams.get("lang"), "en");
  assert.equal(url.searchParams.get("pot"), "not-forwarded");
  assert.equal(url.searchParams.get("fmt"), "json3");
  for (const name of ["kind", "tlang", "name"]) assert.equal(url.searchParams.has(name), false);
  for (const message of h.messages) assert.doesNotMatch(JSON.stringify(message), /pot=|not-forwarded/);

  assert.equal((await h.context.astYoutubeCaptionCapture.requestTarget({ videoId, targetLanguage: "en" })).text, englishText);
  assert.equal(fetched.length, 1);
});

