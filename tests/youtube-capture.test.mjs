import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import vm from "node:vm";

const mainSource = readFileSync(new URL("../extension/content/youtube-capture-main.js", import.meta.url), "utf8");
const bridgeSource = readFileSync(new URL("../extension/content/youtube-capture-bridge.js", import.meta.url), "utf8");
const videoId = "av5DnWZZHnk";
const captionUrl = `https://www.youtube.com/api/timedtext?v=${videoId}&lang=es&kind=asr&fmt=json3&pot=not-forwarded`;
const text = JSON.stringify({ events: [{ tStartMs: 1250, dDurationMs: 2500, segs: [{ utf8: "Hola mundo" }] }] });

function harness() {
  const messages = [];
  const listeners = [];
  const timeouts = new Set();
  const tracks = [{ languageCode: "es", kind: "asr" }, { languageCode: "en" }];
  let selectedTrack = tracks[1];
  let captionsOn = false;
  const player = {
    getPlayerResponse: () => ({ videoDetails: { videoId }, captions: { playerCaptionsTracklistRenderer: { captionTracks: tracks } } }),
    getOption: (_module, option) => option === "tracklist" ? tracks : selectedTrack,
    setOption: (_module, _option, track) => { selectedTrack = track; },
    toggleSubtitles: () => { captionsOn = !captionsOn; },
    querySelector: () => ({ getAttribute: () => String(captionsOn) })
  };
  class Xhr {
    constructor() { this.listeners = []; this.status = 200; }
    open(_method, url) { this.responseURL = url; }
    addEventListener(type, callback) { if (type === "load") this.listeners.push(callback); }
    respond(body) { this.responseText = body; for (const callback of this.listeners.splice(0)) callback(); }
  }
  const context = {
    URL, XMLHttpRequest: Xhr,
    location: { origin: "https://www.youtube.com" },
    document: { getElementById: () => player },
    setTimeout(callback) { timeouts.add(callback); return callback; },
    clearTimeout(callback) { timeouts.delete(callback); }
  };
  const window = {
    fetch: async () => ({ ok: true, url: captionUrl, clone: () => ({ text: async () => text }) }),
    addEventListener(type, listener) { if (type === "message") listeners.push(listener); },
    postMessage(data, origin) {
      messages.push(data);
      for (const listener of listeners) listener({ data, origin, source: window });
    }
  };
  context.window = window;
  return {
    context, window, player, messages, timeouts, tracks,
    get selectedTrack() { return selectedTrack; },
    get captionsOn() { return captionsOn; },
    event(data, source = window, origin = context.location.origin) {
      for (const listener of listeners) listener({ data, source, origin });
    },
    main() { vm.runInNewContext(mainSource, context); },
    bridge() { vm.runInNewContext(bridgeSource, context); },
    xhr(url = captionUrl, body = text, status = 200) {
      const xhr = new Xhr();
      xhr.open("GET", url);
      xhr.status = status;
      xhr.respond(body);
      return xhr;
    }
  };
}

test("YouTube capture observes native XHR without forwarding signed URLs or unrelated data", () => {
  const h = harness();
  h.main();
  h.xhr();
  assert.equal(h.messages.length, 1);
  assert.equal(h.messages[0].caption.text, text);
  assert.deepEqual(Object.keys(h.messages[0].caption).sort(), ["isAutoGenerated", "languageCode", "text", "videoId"]);
  h.xhr(captionUrl, "");
  h.xhr(captionUrl, text, 403);
  h.xhr(captionUrl.replace("www.youtube.com", "example.com"));
  h.xhr(`${captionUrl}&tlang=ko`);
  assert.equal(h.messages.length, 1);
});

test("YouTube capture clones fetch responses and preserves the original promise and response", async () => {
  const h = harness();
  const response = { ok: true, url: captionUrl, clone: () => ({ text: async () => text }) };
  const promise = Promise.resolve(response);
  h.window.fetch = () => promise;
  h.main();
  const result = h.window.fetch(captionUrl);
  assert.equal(result, promise);
  assert.equal(await result, response);
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(h.messages[0].caption.text, text);
});

test("YouTube native capture selects the requested track and restores captions after success", async () => {
  const h = harness();
  h.bridge();
  h.main();
  const request = { videoId, languageCode: "es", isAutoGenerated: true };
  const pending = h.context.astYoutubeCaptionCapture.request(request);
  assert.equal(h.captionsOn, true);
  assert.equal(h.selectedTrack, h.tracks[0]);
  h.xhr();
  const captured = await pending;
  assert.equal(captured.text, text);
  assert.equal(captured.languageCode, "es");
  assert.equal(h.captionsOn, false);
  assert.equal(h.selectedTrack, h.tracks[1]);
  assert.equal(h.timeouts.size, 0);
  assert.equal(h.context.astYoutubeCaptionCapture.get({ ...request, videoId: "another1234" }), null);
  assert.equal(h.context.astYoutubeCaptionCapture.get({ ...request, languageCode: "en" }), null);
  assert.equal(h.context.astYoutubeCaptionCapture.get({ ...request, isAutoGenerated: false }), null);
});

test("YouTube bridge requests replay a response captured before the isolated listener started", async () => {
  const h = harness();
  h.main();
  h.xhr();
  h.bridge();
  const captured = await h.context.astYoutubeCaptionCapture.request({ videoId, languageCode: "es" });
  assert.equal(captured.text, text);
  assert.equal(h.captionsOn, false);
});

test("YouTube capture restores the user's player state when no caption response arrives", async () => {
  const h = harness();
  h.bridge();
  h.main();
  const pending = h.context.astYoutubeCaptionCapture.request({ videoId, languageCode: "es" });
  for (const callback of [...h.timeouts]) callback();
  assert.equal(await pending, null);
  assert.equal(h.captionsOn, false);
  assert.equal(h.selectedTrack, h.tracks[1]);
});

test("YouTube capture refreshes an already enabled native track and leaves it enabled", async () => {
  const h = harness();
  h.player.toggleSubtitles();
  h.bridge();
  h.main();
  const pending = h.context.astYoutubeCaptionCapture.request({ videoId, languageCode: "en", isAutoGenerated: false });
  assert.equal(h.captionsOn, false);
  [...h.timeouts].at(-1)();
  assert.equal(h.captionsOn, true);
  h.xhr(captionUrl.replace("lang=es", "lang=en").replace("&kind=asr", ""));
  assert.equal((await pending).languageCode, "en");
  assert.equal(h.captionsOn, true);
  assert.equal(h.timeouts.size, 0);
});

test("YouTube bridge ignores other frames, origins, invalid bodies, and generic extension commands", () => {
  const h = harness();
  h.bridge();
  const caption = { videoId, languageCode: "es", isAutoGenerated: true, text };
  const data = { type: "ast.youtube.captionData", caption };
  h.event(data, {});
  h.event(data, h.window, "https://example.com");
  h.event({ type: "settings.setActiveProvider", caption });
  h.event({ ...data, caption: { ...caption, text: "x".repeat(2 * 1024 * 1024 + 1) } });
  assert.equal(h.context.astYoutubeCaptionCapture.get({ videoId }), null);
  h.event(data);
  assert.equal(h.context.astYoutubeCaptionCapture.get({ videoId }).text, text);
});

test("YouTube capture does not control a different video and accepts unloaded caption track metadata", () => {
  const h = harness();
  h.main();
  h.window.postMessage({ type: "ast.youtube.captionRequest", request: { videoId: "another1234" } }, h.context.location.origin);
  assert.equal(h.captionsOn, false);
  const originalGetOption = h.player.getOption;
  h.player.getOption = (module, option) => option === "tracklist" ? [] : originalGetOption(module, option);
  h.window.postMessage({ type: "ast.youtube.captionRequest", request: { videoId, languageCode: "es" } }, h.context.location.origin);
  assert.equal(h.captionsOn, true);
  assert.equal(h.selectedTrack, h.tracks[0]);
});

test("YouTube native capture does not switch caption tracks while an ad is playing", async () => {
  const h = harness();
  h.player.classList = { contains: (name) => name === "ad-showing" };
  h.bridge();
  h.main();
  const pending = h.context.astYoutubeCaptionCapture.request({ videoId, languageCode: "es" });
  assert.equal(h.captionsOn, false);
  assert.equal(h.selectedTrack, h.tracks[1]);
  for (const timeout of [...h.timeouts]) timeout();
  assert.equal(await pending, null);
});
