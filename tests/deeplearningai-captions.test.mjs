import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import vm from "node:vm";
import { fetchDeeplearningaiTranscript, isDeeplearningaiCaptionUrl } from "../extension/platforms/deeplearningai-captions.js";
import { parseWebVtt } from "../extension/shared/subtitles.js";
import { validateBackgroundMessage, validateMessageSender } from "../extension/shared/message-contracts.js";

const VTT_URL = "https://video.deeplearning.ai/upv2/course/lc-Video/subtitle/eng/1784217019-c941b3fa445e-eng-a2ab6fe.vtt";

test("DeepLearning.AI caption URLs are limited to the video host's .vtt subtitles", () => {
  assert.equal(isDeeplearningaiCaptionUrl(VTT_URL), true);
  assert.equal(isDeeplearningaiCaptionUrl(VTT_URL.replace(".vtt", ".m3u8")), false);
  assert.equal(isDeeplearningaiCaptionUrl(VTT_URL.replace("video.deeplearning.ai", "evil.example")), false);
  assert.equal(isDeeplearningaiCaptionUrl(VTT_URL.replace("/subtitle/", "/thumbnails/")), false);
  assert.equal(isDeeplearningaiCaptionUrl(VTT_URL.replace("https:", "http:")), false);
});

test("a reversed first cue is repaired instead of failing the lesson", () => {
  const cues = parseWebVtt([
    "WEBVTT", "X-TIMESTAMP-MAP=LOCAL:00:00:00.000,MPEGTS:127826", "",
    "1", "00:00:05.713 --> 00:00:04.400", "Welcome to this course on supervised fine-tuning", "",
    "2", "00:00:04.400 --> 00:00:09.279", "language models.", ""
  ].join("\n"));
  assert.deepEqual(cues.map((cue) => [cue.start, cue.end]), [[0, 4.4], [4.4, 9.279]]);
});

test("DeepLearning.AI VTT becomes a deeplearningai subtitle document", async () => {
  const previousFetch = globalThis.fetch;
  globalThis.fetch = async (url, init) => {
    assert.equal(url, VTT_URL);
    assert.equal(init.redirect, "error");
    return new Response("WEBVTT\n\n1\n00:00:04.400 --> 00:00:09.279\nlanguage models.\n", { status: 200 });
  };
  try {
    const document = await fetchDeeplearningaiTranscript({ lessonId: "rm98gb4q", trackUrl: VTT_URL, sourceLanguage: "en-us" });
    assert.deepEqual(document, {
      platform: "deeplearningai",
      videoId: "rm98gb4q",
      sourceLanguage: "en-us",
      cues: [{ id: "1", start: 4.4, end: 9.279, text: "language models." }]
    });
    await assert.rejects(fetchDeeplearningaiTranscript({ lessonId: "x", trackUrl: "https://evil.example/a.vtt" }), /caption URL is invalid/);
  } finally {
    globalThis.fetch = previousFetch;
  }
});

function loadParser(source) {
  const names = ["normalizeDeeplearningaiCaptionUrl", "parseDeeplearningaiTracksFromHtml"];
  const code = names.map((name) => {
    const start = source.indexOf(`function ${name}(`);
    assert.ok(start >= 0, `${name} exists`);
    return source.slice(start, source.indexOf("\n}\n", start) + 3);
  }).join("\n");
  const sandbox = { URL, JSON, String, Array, Object, Set };
  vm.runInNewContext(`${code}\nthis.parse = parseDeeplearningaiTracksFromHtml;`, sandbox);
  return sandbox.parse;
}

test("lesson page __NEXT_DATA__ yields the lesson video's subtitle tracks", async () => {
  const source = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  const parse = loadParser(source);
  const nextData = {
    props: { pageProps: { videoId: 10172054, trpcState: { json: { queries: [
      { state: { data: { video: { videoId: 10172041, tracks: [{ kind: "subtitles", label: "OTHER", src: VTT_URL.replace("c941", "0000"), srcLang: "en-us" }] } } } },
      { state: { data: { video: {
        videoId: 10172054,
        tracks: [{ kind: "subtitles", label: "ENGLISH", src: VTT_URL, srcLang: "en-us" }, { kind: "subtitles", label: "BAD", src: "https://evil.example/x.vtt", srcLang: "xx" }]
      } } } }
    ] } } } }
  };
  const html = `<html><script id="__NEXT_DATA__" type="application/json">${JSON.stringify(nextData)}</script></html>`;
  const tracks = [...parse(html)].map((track) => ({ ...track }));
  assert.deepEqual(tracks, [{ languageCode: "en-us", label: "ENGLISH", isAutoGenerated: false, trackUrl: VTT_URL }]);

  const withSubtitleMapOnly = JSON.stringify({ props: { pageProps: { videoId: 1, x: { video: { videoId: 1, subtitle: JSON.stringify({ "en-us": { URI: VTT_URL, NAME: "ENGLISH" } }) } } } } });
  assert.equal([...parse(`<script id="__NEXT_DATA__">${withSubtitleMapOnly}</script>`)].length, 1);
  assert.equal(parse("<html>no data</html>").length, 0);
});

test("DeepLearning.AI messages, sender rules, and player wiring", async () => {
  assert.equal(validateBackgroundMessage({ type: "captions.deeplearningai.fetchTranscript", lessonId: "x" }).error, "trackUrl is required.");
  assert.equal(validateBackgroundMessage({ type: "captions.deeplearningai.fetchTranscript", lessonId: "x", trackUrl: VTT_URL }).error, undefined);
  const message = { type: "captions.deeplearningai.fetchTranscript", lessonId: "x", trackUrl: VTT_URL };
  const sender = (url) => ({ id: "extension-id", url, tab: { id: 5, url } });
  assert.equal(validateMessageSender(message, sender("https://learn.deeplearning.ai/courses/c/lesson/rm98gb4q/n"), "extension-id").ok, true);
  assert.equal(validateMessageSender(message, sender("https://learn.deeplearning.ai/account"), "extension-id").ok, false);

  const [contentScript, manifest] = await Promise.all([
    readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8"),
    readFile(new URL("../extension/manifest.json", import.meta.url), "utf8").then(JSON.parse)
  ]);
  assert.ok(manifest.content_scripts[0].matches.includes("https://learn.deeplearning.ai/courses/*"));
  assert.match(contentScript, /host === "learn\.deeplearning\.ai"\) return "deeplearningai"/);
  assert.match(contentScript, /type: "captions\.deeplearningai\.fetchTranscript"/);
  assert.match(contentScript, /const DLAI_VIDEO_SELECTOR = "\.lesson-video-player video"/);
  assert.match(contentScript, /player && \(player\.readyState >= 1 \|\| player\.currentSrc\) \? player : null/);
});

test("older DeepLearning.AI lessons with CloudFront caption files are accepted, still only /subtitle/*.vtt", async () => {
  const cloudfront = "https://dft3h5i221ap1.cloudfront.net/Lamini/finetuning-llm/subtitle/SC-Fine_Tuning_C1_Intro.mp4_en.vtt";
  assert.equal(isDeeplearningaiCaptionUrl(cloudfront), true);
  assert.equal(isDeeplearningaiCaptionUrl("https://dft3h5i221ap1.cloudfront.net/Lamini/finetuning-llm/video/thumbnails/thumbnail.vtt"), false);
  assert.equal(isDeeplearningaiCaptionUrl("https://evil.example/subtitle/a.vtt"), false);

  const source = await readFile(new URL("../extension/content/content-script.js", import.meta.url), "utf8");
  const parse = loadParser(source);
  const nextData = { props: { pageProps: { videoId: 85, trpcState: { json: { queries: [{ state: { data: { video: {
    videoId: 85,
    tracks: [{ kind: "subtitles", label: "ENGLISH", src: cloudfront, srcLang: "en-us" }]
  } } } }] } } } } };
  const tracks = [...parse(`<script id="__NEXT_DATA__" type="application/json">${JSON.stringify(nextData)}</script>`)];
  assert.equal(tracks.length, 1);
  assert.equal(tracks[0].trackUrl, cloudfront);
});
